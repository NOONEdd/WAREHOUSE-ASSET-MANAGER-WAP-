"""Turns out/evaluation-results.json into the committed results document
(docs/security/import-evaluation-results.md), so that no number is copied by
hand. Usage:
    python3 -I report.py RESULTS.json OUTPUT.md [MEASUREMENT.json]
MEASUREMENT.json is a full run whose measurement phase is reported when
RESULTS.json comes from a --quick run (verification under the recorded limits).
"""
import json
import sys

LIMIT_NAMES = {
    "L1": "rows 50,000 and cells 1,000,000 (one sheet)",
    "L2": "worksheets 20 (and cells 1,000,000)",
    "L3": "columns 100 (and cells 1,000,000)",
    "L4": "CSV rows 50,000, cells 1,000,000, size just under 10 MiB",
    "L5": "ZIP entries 1,000",
    "L6": "decompressed 99.3 MiB (ceiling 100 MiB)",
    "L7": "compressed 9.4 MiB of incompressible text",
    "L8": "compressed exactly 10 MiB (10,485,760 bytes)",
    "L9": "CSV with exactly 100 columns",
    "L10": "CSV of exactly 10 MiB (10,485,760 bytes)",
    "L11": "decompressed exactly 100 MiB (104,857,600 bytes)",
    "O1": "worksheets 21",
    "O2": "rows 50,001",
    "O3": "column 101",
    "O4": "cells 1,000,001",
    "O5": "ZIP entries 1,001",
    "O6": "decompressed 100 MiB + 1 byte",
    "O7": "compressed 10 MiB + 1 byte",
    "O8": "CSV rows 50,001",
    "O9": "CSV columns 101",
    "O10": "CSV 10 MiB + 1 byte",
}


def cell(v):
    return str(v if v is not None else "").replace("|", "/").replace("\n", " ")


def main(src, dst, measured=None):
    r = json.load(open(src, encoding="utf-8"))
    m_run = json.load(open(measured, encoding="utf-8")) if measured else r
    verify = r["phases"]["verify"]
    by_id = {v["id"]: v for v in verify}
    out = []
    w = out.append
    h = r["host"]
    w("# Spreadsheet import evaluation: results of the final run")
    w("")
    w(f"Generated by `tools/import-evaluation/report.py` from `out/evaluation-results.json`. Run started {r['started']}, finished {r['finished']}.")
    w(f"Host: Node {h['node']}, {h['cores']} cores ({h['cpu']}), {h['totalMemMiB']} MiB RAM, Linux {h['kernel']}; network namespace available: {h['networkNamespace']}.")
    w(f"Synthetic files only. Limits used for verification: heap {r['limitsUsed']['heapMiB']} MiB, resident-memory watchdog {r['limitsUsed']['rssMiB']} MiB, kernel data limit {r['limitsUsed']['dataMiB']} MiB; wall clock 30 s.")
    s = r["summary"]
    w("")
    w(f"**Summary:** {s['cases']} cases, failures: {', '.join(s['failures']) or 'none'}; load() deterministic with intact text: {s['streamOk']}; load test: {s['loadOk']}; every isolation layer acted: {s['isolationOk']}.")

    if "measure" in m_run["phases"]:
        d = m_run["phases"]["derive"]
        w("")
        w("## Measurement with generous limits (heap 6,144 MiB)")
        w("")
        if m_run is not r:
            w(f"From the full run started {m_run['started']}, whose derived limits are the recorded ones used below.")
            w("")
        w("| Case | What | Time ms | Peak resident MiB | Peak VmData MiB | File bytes |")
        w("|---|---|---|---|---|---|")
        for m in m_run["phases"]["measure"]:
            w(f"| {m['id']} | {cell(m['title'])} | {m['wallMs']} | {m['peakRssMiB']} | {m['peakVmDataMiB']} | {m['inputBytes']:,} |")
        w("")
        w(f"Smallest heap ceiling at which every at-limit file parses: **{d['minHeapThatPasses']} MiB**. Peaks: resident {d['peakRssMiB']} MiB, VmData {d['peakVmDataMiB']} MiB. Derived: heap {d['derived']['heapMiB']} MiB, watchdog {d['derived']['rssMiB']} MiB, kernel {d['derived']['dataMiB']} MiB.")

    w("")
    w("## E-18 boundaries")
    w("")
    w("| Case | Ceiling tested | Expected | Result | Time ms | Peak MiB | Message |")
    w("|---|---|---|---|---|---|---|")
    for cid in LIMIT_NAMES:
        v = by_id.get(cid)
        if v is None:
            continue
        w(f"| {cid} | {LIMIT_NAMES[cid]} | {v['expect']} | {'pass' if v['pass'] else '**FAIL**'}: {v['got']} | {v['wallMs']} | {v['peakRssMiB']} | {cell(v.get('note') or (v.get('detail') if v['got'] != 'ok' else ''))} |")

    w("")
    w("## All cases under the recommended limits")
    w("")
    w("| Case | Group | What | Expected | Result | Time ms | Peak MiB | Detail |")
    w("|---|---|---|---|---|---|---|---|")
    for v in verify:
        w(f"| {v['id']} | {v['group']} | {cell(v['title'])} | {v['expect']} | {'pass' if v['pass'] else '**FAIL**'}: {v['got']} | {cell(v.get('wallMs'))} | {cell(v.get('peakRssMiB'))} | {cell(v.get('note') or (v.get('detail') if v['got'] != 'ok' else ''))} |")

    w("")
    w("## load() repeatability and the streaming reader")
    w("")
    w("| File | load() twice, same rows | Streaming reader, confined | Streaming reader, temp files allowed | Same rows as load() | Rows with damaged text: load() / stream |")
    w("|---|---|---|---|---|---|")
    for e in r["phases"]["stream"]:
        w(f"| {e['id']} | {cell(e.get('loadTwiceSameDigest'))} | {cell(e.get('streamConfined'))} {cell(e.get('streamConfinedDetail'))} | {cell(e.get('streamWithTempFiles'))} | {cell(e.get('streamDigestEqualsLoad'))} | {cell(e.get('loadRowsWithDamagedText'))} / {cell(e.get('streamRowsWithDamagedText'))} |")

    w("")
    w("## Isolation layers (deliberately misbehaving child)")
    w("")
    w("| Probe | Outcome | Stopped by | Time ms | Peak MiB | Details |")
    w("|---|---|---|---|---|---|")
    for p in r["phases"]["isolation"]:
        res = p.get("result") or {}
        details = {k: v for k, v in res.items() if k not in ("ok", "rssKiB", "maxRssKiB")}
        w(f"| {cell(p['name'])} | {p['outcome']} | {cell(p.get('reason'))} | {p['wallMs']} | {p['peakRssMiB']} | {cell(json.dumps(details, ensure_ascii=False) if details else p.get('stderrHead'))} |")

    w("")
    w("## Four parses at the same time")
    w("")
    w("| File | Outcomes | Time per parse ms | Peak MiB per parse | Same rows in all four | Total ms |")
    w("|---|---|---|---|---|---|")
    for l in r["phases"]["load"]:
        w(f"| {l['id']} | {', '.join(l['outcomes'])} | {', '.join(map(str, l['wallMs']))} | {', '.join(map(str, l['peakRssMiB']))} | {l['sameDigest']} | {l['totalMs']} |")
    w("")
    open(dst, "w", encoding="utf-8").write("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else None)
